fn validate_vrl(vrl: &str) -> Result<(), VrlGeneratorError> {
    // Basic validation
    if vrl.is_empty() {
        return Err(VrlGeneratorError::ValidationFailed("Empty VRL".into()));
    }
    if vrl.contains("```") || vrl.contains("```vrl") {
        return Err(VrlGeneratorError::ValidationFailed("Contains markdown formatting".into()));
    }
    if !vrl.contains(".class_uid =") {
        return Err(VrlGeneratorError::ValidationFailed("Missing .class_uid".into()));
    }
    if !vrl.contains(".category_uid =") {
        return Err(VrlGeneratorError::ValidationFailed("Missing .category_uid".into()));
    }
    if !vrl.contains(".type_uid =") {
        return Err(VrlGeneratorError::ValidationFailed("Missing .type_uid".into()));
    }
    if vrl.contains(":=") {
        return Err(VrlGeneratorError::ValidationFailed("Contains := assignment".into()));
    }
    Ok(())
}

