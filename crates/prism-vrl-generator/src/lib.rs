fn shown_samples(samples: &[String]) -> String {
    samples.iter().take(5).enumerate().map(|(i, s)| format!("{}. {}", i+1, s)).collect::<Vec<_>>().join("\n")
}

fn infer_ocsf_path(source_field: &str) -> String {
    let field = source_field.to_ascii_lowercase();
    // Map common source field names to OCSF paths
    match field.as_str() {
        "srcip" | "src_ip" | "source_ip" | "saddr" | "src" => "src_endpoint.ip".to_string(),
        "dstip" | "dst_ip" | "destination_ip" | "daddr" | "dst" => "dst_endpoint.ip".to_string(),
        "srcport" | "src_port" | "source_port" | "sport" | "spt" => "src_endpoint.port".to_string(),
        "dstport" | "dst_port" | "destination_port" | "dport" | "dpt" => "dst_endpoint.port".to_string(),
        "proto" | "protocol" | "ipproto" => "connection_info.protocol_name".to_string(),
        "action" | "act" => "event.action".to_string(),
        "level" | "severity" | "severity_id" => "severity".to_string(),
        "devname" | "hostname" | "device" => "device.hostname".to_string(),
        "user" | "username" | "srcuser" | "ruser" => "actor.user.name".to_string(),
        "url" | "request" | "uri" | "requesturl" => "url.url_string".to_string(),
        "method" | "http_method" => "http.request.method".to_string(),
        "status" | "http_status" => "http.response.status_code".to_string(),
        "file" | "filename" | "file_name" => "file.name".to_string(),
        "path" | "filepath" | "file_path" => "file.path".to_string(),
        "message" | "msg" | "evt" => "message".to_string(),
        _ => "".to_string(),
    }
}

