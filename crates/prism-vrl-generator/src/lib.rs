#[derive(Error, Debug)]
pub enum VrlGeneratorError {
    #[error("VRL compilation failed: {0}")]
    CompilationFailed(String),
    #[error("Dry-run failed: {0}")]
    DryRunFailed(String),
    #[error("LLM request failed: {0}")]
    LlmRequestFailed(String),
    #[error("Validation failed: {0}")]
    ValidationFailed(String),
}

#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct VrlScript {
    pub content: String,
    pub class_uid: i64,
    pub category_uid: i64,
    pub type_uid: i64,
    pub field_count: usize,
    pub validation_passed: bool,
    pub warnings: Vec<String>,
}

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum GeneratorMode {
    Heuristic,
    FineTuned,
    Llm,
}

pub struct VrlGenerator {
    mode: GeneratorMode,
    llm_client: Option<LlmClient>,
    fine_tuned_model_path: Option<String>,
}

#[derive(Clone)]
struct LlmClient {
    endpoint: String,
    model: String,
    client: reqwest::Client,
}

impl VrlGenerator {
    pub fn heuristic() -> Self {
        Self {
            mode: GeneratorMode::Heuristic,
            llm_client: None,
            fine_tuned_model_path: None,
        }
    }

    pub fn fine_tuned(model_path: String) -> Self {
        Self {
            mode: GeneratorMode::FineTuned,
            llm_client: None,
            fine_tuned_model_path: Some(model_path),
        }
    }

    pub fn llm(endpoint: String, model: String) -> Self {
        Self {
            mode: GeneratorMode::Llm,
            llm_client: Some(LlmClient {
                endpoint,
                model,
                client: reqwest::Client::new(),
            }),
            fine_tuned_model_path: None,
        }
    }

    pub fn generate(&self, samples: &[String], profile: &SourceProfile) -> Result<VrlScript, VrlGeneratorError> {
        match self.mode {
            GeneratorMode::Heuristic => self.generate_heuristic(samples, profile),
            GeneratorMode::FineTuned => self.generate_fine_tuned(samples, profile),
            GeneratorMode::Llm => self.generate_llm(samples, profile),
        }
    }

    fn generate_heuristic(&self, samples: &[String], profile: &SourceProfile) -> Result<VrlScript, VrlGeneratorError> {
        let mut lines = Vec::new();
        lines.push("# Generated by prism-vrl-generator heuristic-v1".to_string());
        lines.push(format!("# Class: {} ({})", class_name(profile.suggested_class_uid.unwrap_or(4001)), profile.suggested_class_uid.unwrap_or(4001)));
        lines.push("".to_string());

        // Decoder chain
        for decoder in &profile.decoder_chain {
            lines.push(format!(". = parse_{}!(.message)", decoder.to_lowercase().replace("(", "_").replace(")", "")));
        }
        if profile.decoder_chain.is_empty() {
            lines.push(".message = parse_regex!(string!(.message), r'(?P<msg>.*)').msg".to_string());
        }
        lines.push("".to_string());

        // Field extractions from profile.field_map
        for (ocsf_path, source_field) in &profile.field_map {
            if ocsf_path.starts_with("src_endpoint.") || ocsf_path.starts_with("dst_endpoint.") {
                let field_name = source_field.to_lowercase().replace(".", "_");
                lines.push(format!(
                    ".{} = parse_regex!(string!(.message), r'{}=(?P<val>[^\\s]+)').val",
                    ocsf_path, source_field
                ));
            }
        }

        // Standard OCSF fields
        lines.push(format!(".class_uid = {}", profile.suggested_class_uid.unwrap_or(4001)));
        lines.push(format!(".category_uid = {}", category_uid_for_class(profile.suggested_class_uid.unwrap_or(4001))));
        lines.push(format!(".type_uid = {}", type_uid_for_class(profile.suggested_class_uid.unwrap_or(4001))));
        lines.push(".src_endpoint.ip = .srcip".to_string());
        lines.push(".dst_endpoint.ip = .dstip".to_string());

        // Add severity and action based on available fields
        if profile.field_map.contains_key("event.action") || profile.field_map.contains_key("action") {
            lines.push(".event.action = .action".to_string());
        }
        if profile.field_map.contains_key("severity") || profile.field_map.contains_key("level") {
            lines.push(".severity = .level".to_string());
        }

        let content = lines.join("\n");
        validate_vrl(&content)?;

        Ok(VrlScript {
            content,
            class_uid: profile.suggested_class_uid.unwrap_or(4001),
            category_uid: profile.suggested_class_uid.map(category_uid_for_class).unwrap_or(4),
            type_uid: type_uid_for_class(profile.suggested_class_uid.unwrap_or(4001)),
            field_count: profile.field_map.len(),
            validation_passed: true,
            warnings: vec!["Generated by heuristic mode - review before deployment".to_string()],
        })
    }

    fn generate_fine_tuned(&self, samples: &[String], profile: &SourceProfile) -> Result<VrlScript, VrlGeneratorError> {
        // TODO: Implement fine-tuned model inference
        // For now, fall back to heuristic
        self.generate_heuristic(samples, profile)
    }

    fn generate_llm(&self, samples: &[String], profile: &SourceProfile) -> Result<VrlScript, VrlGeneratorError> {
        let Some(client) = &self.llm_client else {
            return Err(VrlGeneratorError::LlmRequestFailed("No LLM client configured".into()));
        };

        let prompt = build_llm_prompt(samples, profile);
        let response = client.complete(prompt).await?;

        let vrl = extract_vrl_from_response(&response)?;
        validate_vrl(&vrl)?;

        Ok(VrlScript {
            content: vrl,
            class_uid: profile.suggested_class_uid.unwrap_or(4001),
            category_uid: profile.suggested_class_uid.map(category_uid_for_class).unwrap_or(4),
            type_uid: type_uid_for_class(profile.suggested_class_uid.unwrap_or(4001)),
            field_count: profile.field_map.len(),
            validation_passed: true,
            warnings: vec!["Generated by LLM - review before deployment".to_string()],
        })
    }

    pub async fn validate_and_score(&self, vrl: &str, samples: &[String]) -> Result<ScoreReport, VrlGeneratorError> {
        // Compile VRL
        let compiled = compile_vrl(vrl)?;

        // Dry-run with samples
        let mut total_fields = 0;
        let mut matched_fields = 0;

        for sample in samples {
            let result = run_dry_run(vrl, sample)?;
            let fields = extract_fields(&result)?;
            total_fields += fields.len();
            for (path, _) in fields {
                if profile.field_map.contains_key(&path) {
                    matched_fields += 1;
                }
            }
        }

        let field_accuracy = if total_fields > 0 {
            matched_fields as f64 / total_fields as f64
        } else {
            0.0
        };

        Ok(ScoreReport {
            vrl_compile_passed: true,
            dry_run_passed: true,
            fixtures_total: samples.len(),
            fixtures_passed: samples.len(),
            field_accuracy,
            ocsf_validation_passed: true,
            unknown_paths: Vec::new(),
            overall_score: field_accuracy * 0.5 + 0.5,
        })
    }
}

#[derive(Debug, Serialize, Deserialize)]
pub struct ScoreReport {
    pub vrl_compile_passed: bool,
    pub dry_run_passed: bool,
    pub fixtures_total: usize,
    pub fixtures_passed: usize,
    pub field_accuracy: f64,
    pub ocsf_validation_passed: bool,
    pub unknown_paths: Vec<String>,
    pub overall_score: f64,
}

impl LlmClient {
    async fn complete(&self, prompt: String) -> Result<String, VrlGeneratorError> {
        let req = serde_json::json!({
            "model": self.model,
            "prompt": prompt,
            "stream": false,
            "options": {
                "temperature": 0.1,
                "num_predict": 1024,
                "repeat_penalty": 1.1,
                "repeat_last_n": 64,
            }
        });

        let resp = self.client
            .post(&format!("{}/api/generate", self.endpoint))
            .json(&req)
            .timeout(std::time::Duration::from_secs(60))
            .send()
            .await
            .map_err(|e| VrlGeneratorError::LlmRequestFailed(e.to_string()))?;

        if !resp.status().is_success() {
            return Err(VrlGeneratorError::LlmRequestFailed(format!("HTTP {}", resp.status())));
        }

        let data: serde_json::Value = resp.json().await.map_err(|e| VrlGeneratorError::LlmRequestFailed(e.to_string()))?;
        Ok(data["response"].as_str().unwrap_or("").to_string())
    }
}

