    #[test]
    fn test_compile_vrl_valid() {
        let vrl = r#"
.class_uid = 4001
.category_uid = 4
.type_uid = 400101
matched, err = parse_regex(string!(.message), r'(?i)srcip=(?P<val>[^\s,"]+)')
if err == null {
    .src_endpoint.ip = matched.val
}
.test_port = to_int("123") ?? null
"#;
        assert!(compile_vrl(vrl).is_ok());
        let res = run_dry_run(vrl, "no match here").unwrap();
        assert_eq!(res["class_uid"], 4001);
        assert_eq!(res["test_port"], 123);
        let res2 = run_dry_run(vrl, "srcip=1.2.3.4 foo=bar").unwrap();
        assert_eq!(res2["src_endpoint"]["ip"], "1.2.3.4");
    }

