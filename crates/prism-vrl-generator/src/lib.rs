fn validate_vrl(vrl: &str) -> Result<(), VrlGeneratorError> {
    // Basic validation
    if vrl.is_empty() {
        return Err(VrlGeneratorError::ValidationFailed("Empty VRL".into()));
    }
    if vrl.contains("```") || vrl.contains("```vrl") {
        return Err(VrlGeneratorError::ValidationFailed("Contains markdown formatting".into()));
    }
    if !vrl.contains(".class_uid =") {
        return Err(VrlGeneratorError::ValidationFailed("Missing .class_uid".into()));
    }
    if !vrl.contains(".category_uid =") {
        return Err(VrlGeneratorError::ValidationFailed("Missing .category_uid".into()));
    }
    if !vrl.contains(".type_uid =") {
        return Err(VrlGeneratorError::ValidationFailed("Missing .type_uid".into()));
    }
    if vrl.contains(":=") {
        return Err(VrlGeneratorError::ValidationFailed("Contains := assignment".into()));
    }
    compile_vrl(vrl)?;
    Ok(())
}

pub fn compile_vrl(vrl_str: &str) -> Result<(), VrlGeneratorError> {
    if vrl_str.trim().is_empty() {
        return Err(VrlGeneratorError::CompilationFailed("Empty VRL".into()));
    }
    let fns = vrl::stdlib::all();
    vrl::compiler::compile(vrl_str, &fns)
        .map_err(|e| VrlGeneratorError::CompilationFailed(format!("{:?}", e)))?;
    Ok(())
}

pub fn run_dry_run(vrl_str: &str, sample: &str) -> Result<serde_json::Value, VrlGeneratorError> {
    let fns = vrl::stdlib::all();
    let res = vrl::compiler::compile(vrl_str, &fns)
        .map_err(|e| VrlGeneratorError::CompilationFailed(format!("{:?}", e)))?;

    let mut map = std::collections::BTreeMap::new();
    map.insert("message".into(), vrl::value::Value::from(sample));
    let value = vrl::value::Value::Object(map);

    let mut target = vrl::compiler::TargetValue {
        value,
        metadata: vrl::value::Value::Object(std::collections::BTreeMap::new()),
        secrets: vrl::value::Secrets::new(),
    };

    let mut state = vrl::compiler::state::RuntimeState::default();
    let tz = vrl::compiler::TimeZone::default();
    let mut ctx = vrl::compiler::Context::new(&mut target, &mut state, &tz);

    res.program
        .resolve(&mut ctx)
        .map_err(|e| VrlGeneratorError::DryRunFailed(format!("{:?}", e)))?;

    serde_json::to_value(&target.value)
        .map_err(|e| VrlGeneratorError::DryRunFailed(e.to_string()))
}

pub fn extract_fields(result: &serde_json::Value) -> Result<Vec<String>, VrlGeneratorError> {
    let mut fields = Vec::new();
    collect_fields("", result, &mut fields);
    Ok(fields)
}

fn collect_fields(prefix: &str, val: &serde_json::Value, fields: &mut Vec<String>) {
    if let serde_json::Value::Object(map) = val {
        for (k, v) in map {
            let full = if prefix.is_empty() {
                k.clone()
            } else {
                format!("{}.{}", prefix, k)
            };
            fields.push(full.clone());
            collect_fields(&full, v, fields);
        }
    }
}

